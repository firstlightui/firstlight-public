        <h1>Firstlight Showcase Privacy Policy</h1>
        <p class="text-(--site-muted)">Last updated: <time datetime="2026-10-25">25 October 2026</time></p>

        <p>Firstlight Showcase is an interactive native interface reference from Firstlight UI. No account is required.</p>

        <h2>Data collection</h2>
        <p>The app does not transmit your form entries, selected media or usage history to Firstlight UI. It contains no advertising or analytics SDKs.</p>

        <h2>On-device data</h2>
        <p>Sample records, preferences and media you choose are processed in the app on your device. Some are saved in local app storage. Device backups may include app data according to your operating system and backup settings. Deleting the app removes its local app data; copies in backups are managed through your backup service.</p>

        <h2>Camera, photos and files</h2>
        <p>The Media examples can use the camera or system photo and document pickers when you choose those actions. Selected files may be copied into the app's local storage so you can try previewing, cropping and validation. The app does not upload them. Clear controls remove the copies currently selected on the Media screen. Earlier copies may remain in app storage until the app is deleted. Permission can be managed in device settings.</p>

        <h2>Sample content</h2>
        <p>Bookings, messages and other example records are fictional. Booking actions do not make real reservations or charge money. The settings recipe saves sample preferences locally and does not send email or register push notifications.</p>

        <h2>Apple and Google services</h2>
        <p>Documentation, code examples and screenshots are included in the app and can be read offline. External references open in your browser only when you choose them. Those websites receive the normal browser request and follow their own privacy policies.</p>
        <p>The App Store, Google Play, operating system diagnostics and device backup services are governed by their providers' privacy policies and your settings. If you contact support, Firstlight UI receives the information you choose to include and uses it to respond.</p>

